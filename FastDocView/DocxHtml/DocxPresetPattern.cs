    /// <summary>The 8 rows, top first, of a preset's cell; null when the name is no preset.</summary>
    public static byte[]? Rows(string preset)
    {
        if (!PresetToHatch.TryGetValue(preset, out string? hatch) || !HatchBottomUp.TryGetValue(hatch, out byte[]? rows)) return null;
        var topDown = (byte[])rows.Clone();
        Array.Reverse(topDown);
        return topDown;
    }

