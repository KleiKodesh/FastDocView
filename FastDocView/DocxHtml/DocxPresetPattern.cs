/// <summary>
/// The 8 x 8 cell of each DrawingML preset pattern (ECMA-376 Part 1 20.1.10.51 ST_PresetPatternVal). The names are the GDI+
/// hatch styles' (pct5 = 5 percent, dnDiag = downward diagonal = HatchStyleForwardDiagonal "\", lgGrid = the large grid =
/// HatchStyleCross, ...); the cells are GDI+'s hatch brush bitmaps as Wine's gdiplus implements them (dlls/gdiplus/brush.c
/// HatchBrushes :203-257, one byte per row, 0x80 = the left pixel; the rows are bottom-up there - drawn into a bottom-up DIB,
