# Prints the advance widths (em fractions, ASCII 32-126) of the chart fonts from the font files' own hmtx tables, as the C# table
# in FastDocView/DocxHtml/DocxChartFontWidths.cs.  python scripts/chart-font-widths.py > FastDocView/DocxHtml/DocxChartFontWidths.cs
import sys
from fontTools.ttLib import TTFont, TTCollection
FONTS = [("Calibri", r"C:\Windows\Fonts\calibri.ttf", None), ("Cambria", r"C:\Windows\Fonts\cambria.ttc", 0),
         ("Times New Roman", r"C:\Windows\Fonts\times.ttf", None), ("Arial", r"C:\Windows\Fonts\arial.ttf", None)]
print("namespace FastDocView.DocxHtml;\n")
print("/// <summary>Advance widths (em fractions) of ASCII 32-126 in the fonts Word charts use, read from each font's hmtx table")
print("/// (generated by scripts/chart-font-widths.py from the Windows font files; Liberation Sans / Tinos / Carlito share Arial's /")
print("/// Times New Roman's / Calibri's metrics). Other characters take the font's average width.")
print("/// WinDescent: OS/2 usWinDescent / unitsPerEm (the depth Word lays a chart text line out with).</summary>")
print("internal static class DocxChartFontWidths\n{")
print("    public static readonly (string Name, double Average, double WinDescent, double[] Widths)[] Fonts =\n    [")
for name, path, index in FONTS:
    font = TTCollection(path).fonts[index] if index is not None else TTFont(path)
    upem = font["head"].unitsPerEm; cmap = font.getBestCmap(); hmtx = font["hmtx"]
    widths = [hmtx[cmap[c]][0] / upem if c in cmap else 0.5 for c in range(32, 127)]
    average = font["OS/2"].xAvgCharWidth / upem
    print('        ("%s", %.4f, %.4f, [%s]),' % (name, average, font["OS/2"].usWinDescent / upem, ", ".join("%.4f" % w for w in widths)))
print("    ];\n")
# Hebrew (U+0590-05FF) is drawn by Word in the complex-script font; with Office's theme defaults that is Arial (Word's PDF of the
# Word-made fixture draws its Hebrew names in ArialMT)
arial = TTFont(r"C:\Windows\Fonts\arial.ttf"); upem = arial["head"].unitsPerEm; cmap = arial.getBestCmap(); hmtx = arial["hmtx"]
print("    /// <summary>Arial's advance widths (em) of U+0590-05FF: Hebrew in Word charts with Office's default complex-script font.</summary>")
print("    public static readonly double[] Hebrew = [%s];" % ", ".join("%.4f" % (hmtx[cmap[c]][0] / upem if c in cmap else 0.0) for c in range(0x590, 0x600)))
print("}")
