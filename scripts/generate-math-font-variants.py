"""Generates FastDocView/Html/WordMathFontVariants.cs from the OpenType MATH table (MathVariants: vertical glyph variants and
glyph assemblies) of the math fonts Word offers on Windows: Cambria Math (cambria.ttc) and DejaVu Math TeX Gyre.
For each stretchable delimiter / n-ary operator: its size variants as (advance height, advance width) in em and the widest
part of its assembly. Run: python scripts/generate-math-font-variants.py (fontTools)."""
from fontTools.ttLib import TTCollection, TTFont
FONTS = [("Cambria Math", lambda: TTCollection(r"C:\Windows\Fonts\cambria.ttc").fonts[1]),
         ("DejaVu Math TeX Gyre", lambda: TTFont(r"C:\Windows\Fonts\DejaVuMathTeXGyre.ttf"))]
CHARS = "()[]{}|\u2016\u27e8\u27e9\u2308\u2309\u230a\u230b\u222b\u222c\u222d\u222e\u222f\u2230\u2211\u220f\u2210\u22c3\u22c2\u22c1\u22c0\u2a01\u2a02\u2a00\u2a04\u2a06"
out = ["// <auto-generated> by scripts/generate-math-font-variants.py from the fonts' OpenType MATH tables - do not edit.",
       "namespace FastDocView.Html;", "",
       "/// <summary>Vertical size variants (advance height, advance width; em) and the widest assembly part (em) of the stretchable",
       "/// delimiters and n-ary operators of the math fonts Word offers on Windows (OpenType MATH: MathVariants).</summary>",
       "internal static class WordMathFontVariants", "{",
       "    public static readonly Dictionary<string, Dictionary<string, (double[] heights, double[] widths, double assemblyWidth)>> Fonts = new(StringComparer.OrdinalIgnoreCase)", "    {"]
for name, load in FONTS:
    f = load(); upem = f["head"].unitsPerEm; v = f["MATH"].table.MathVariants; cmap = f.getBestCmap(); hm = f["hmtx"]
    cov = v.VertGlyphCoverage.glyphs
    out.append(f'        ["{name}"] = new(System.StringComparer.Ordinal)')
    out.append("        {")
    for ch in CHARS:
        g = cmap.get(ord(ch))
        if g is None or g not in cov: continue
        c = v.VertGlyphConstruction[cov.index(g)]
        hs = [r.AdvanceMeasurement / upem for r in c.MathGlyphVariantRecord]
        ws = [hm[r.VariantGlyph][0] / upem for r in c.MathGlyphVariantRecord]
        aw = max((hm[p.glyph][0] / upem for p in c.GlyphAssembly.PartRecords), default=0) if c.GlyphAssembly else 0
        fmt = lambda xs: ", ".join(f"{x:.3f}" for x in xs)
        out.append('            ["' + chr(92) + f'u{ord(ch):04X}"] = (new[] {{ {fmt(hs)} }}, new[] {{ {fmt(ws)} }}, {aw:.3f}),')
    out.append("        },")
out += ["    };", "}", ""]
open(r"FastDocView\Html\WordMathFontVariants.cs", "w", encoding="utf-8", newline="\n").write("\n".join(out))
