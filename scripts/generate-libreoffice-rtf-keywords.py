"""Generates FastDocView.Tests/LibreOfficeRtfKeywords.cs: every control word in LibreOffice's RTF keyword table.

Input: LibreOffice core master sw/source/writerfilter/rtftok/rtftokenizer.cxx (downloaded by the caller).
Usage: python scripts/generate-libreoffice-rtf-keywords.py <rtftokenizer.cxx> FastDocView.Tests/LibreOfficeRtfKeywords.cs
The RTF audit uses it to tell real control words from words no RTF reader knows (LibreOffice ignores those:
rtftokenizer.cxx dispatchKeyword, "unknown keyword" -> skipped / ignored).
"""
import re
import sys

source, output = sys.argv[1], sys.argv[2]
text = open(source, encoding='utf-8').read()
names = sorted(set(re.findall(r'\{\s*"([A-Za-z]+)"_ostr\s*,\s*\{\s*RTFControlType::', text)))
with open(output, 'w', encoding='utf-8', newline='\n') as out:
    out.write('// <auto-generated> by scripts/generate-libreoffice-rtf-keywords.py from LibreOffice core master\n')
    out.write('// sw/source/writerfilter/rtftok/rtftokenizer.cxx (its keyword table). Do not edit by hand; regenerate. </auto-generated>\n')
    out.write('namespace FastDocView.Tests;\n\n')
    out.write('/// <summary>Every control word LibreOffice\'s RTF tokenizer knows (' + str(len(names)) + ' words).</summary>\n')
    out.write('public static class LibreOfficeRtfKeywords\n{\n    public static readonly HashSet<string> All = new(StringComparer.Ordinal)\n    {\n')
    for i in range(0, len(names), 12):
        out.write('        ' + ', '.join('"' + n + '"' for n in names[i:i + 12]) + ',\n')
    out.write('    };\n}\n')
print(len(names), 'keywords')
