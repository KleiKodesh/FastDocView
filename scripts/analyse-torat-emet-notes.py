"""Finds the short note lines that sit between a Torat Emet book's "$ " title and its first section heading.

Usage: python -I analyse-torat-emet-notes.py <books folder> [<books folder> ...] [--min N] [--dump candidates.txt]
Reads every .txt as cp1255. For each file with a "$ " title and a LATER section heading (hash, at, caret, tilde + space), collects the plain
non-blank non-comment lines between them (at most 5 lines after the title, at most 120 chars), normalises them (trim, collapse spaces, drop
trailing punctuation; inline tags removed; a line needs a Hebrew letter) and counts the files that share each text. Prints ASCII only (hash, length, count, code points). Lines found in
at least --min files (default 3) are the note candidates; --dump writes them (UTF-8, one per line); --emit-cs writes the C# data file
(ToratEmetNotes.Data.cs, ASCII only: every character as a unicode escape) that ToratEmetNotes.cs reads.
"""
import sys, os, re, hashlib, collections

MAX_LINES, MAX_CHARS = 5, 120
TRAIL = ' \t.,;:!?-׃־'

def normalise(text):
    text = re.sub(r'<[^<>]*>', '', text)       # inline tags (b, big, small, br ...) are not part of the note's text
    text = re.sub(r'\s+', ' ', text.strip())
    return text.rstrip(TRAIL).lstrip(' ')

def hasHebrew(text):
    return any('א' <= c <= 'ת' for c in text)

def scan(path):
    raw = open(path, 'rb').read().decode('cp1255', errors='replace')
    lines = raw.splitlines()
    title = next((i for i, l in enumerate(lines[:100]) if l.startswith('$ ')), None)
    if title is None: return None
    heading = next((i for i in range(title + 1, len(lines)) if lines[i][:2] in ('# ', '@ ', '^ ', '~ ')), None)
    if heading is None: return None
    found = []
    for l in lines[title + 1:heading]:
        t = l.strip()
        if not t or t.startswith('//'): continue
        if len(found) >= MAX_LINES: break
        if len(t) <= MAX_CHARS and not (len(t) >= 2 and t[1] == ' ' and t[0] in '$#@^~!'):
            n = normalise(t)
            if hasHebrew(n): found.append(n)       # a line with no Hebrew letter (a tag, a script call) is never a note
    return found

def main():
    args = sys.argv[1:]
    minimum = 3; dump = None; emit = None; roots = []
    i = 0
    while i < len(args):
        if args[i] == '--min': minimum = int(args[i + 1]); i += 2
        elif args[i] == '--emit-cs': emit = args[i + 1]; i += 2
        elif args[i] == '--dump': dump = args[i + 1]; i += 2
        else: roots.append(args[i]); i += 1
    counts = collections.Counter(); sample = {}; files = 0; withLines = 0
    for root in roots:
        for d, _, names in os.walk(root):
            for n in names:
                if not n.lower().endswith('.txt'): continue
                found = scan(os.path.join(d, n))
                if found is None: continue
                files += 1
                if found: withLines += 1
                for t in set(x for x in found if x): counts[t] += 1; sample[t] = t
    print('files with title+heading:', files, ' with candidate lines:', withLines)
    ranked = counts.most_common()
    print('distinct texts:', len(ranked), ' ==1:', sum(1 for _, c in ranked if c == 1), ' ==2:', sum(1 for _, c in ranked if c == 2), ' >=%d:' % minimum, sum(1 for _, c in ranked if c >= minimum))
    covered = 0
    for t, c in ranked:
        if c < minimum: break
        covered += c
        print('%4d files  len %3d  sha1 %s  cp %s' % (c, len(t), hashlib.sha1(t.encode('utf-8')).hexdigest()[:8], ' '.join('%04X' % ord(ch) for ch in t)))
    print('file-line coverage by candidates:', covered)
    if emit: emit_cs(emit, [t for t, c in ranked if c >= minimum])
    if dump:
        with open(dump, 'w', encoding='utf-8') as f:
            for t, c in ranked:
                if c >= minimum: f.write(t + '\n')

def emit_cs(path, texts):
    bad = chr(92) + chr(34)
    def esc(t):
        return ''.join(c if 0x20 <= ord(c) < 0x7f and c not in bad else chr(92) + 'u%04X' % ord(c) for c in t)
    with open(path, 'w', encoding='ascii', newline=chr(10)) as f:
        nl = chr(10)
        f.write('// Generated by scripts/analyse-torat-emet-notes.py --emit-cs - do not edit by hand (see ToratEmetNotes.cs).' + nl)
        f.write('namespace FastDocView.Markup;' + nl + nl + 'public static partial class ToratEmetNotes' + nl + '{' + nl)
        f.write('    /// <summary>Normalised texts found as note lines in at least 3 books (%d texts).</summary>' % len(texts) + nl)
        f.write('    private static readonly string[] Listed =' + nl + '    {' + nl)
        for t in sorted(texts):
            f.write('        ' + chr(34) + esc(t) + chr(34) + ',' + nl)
        f.write('    };' + nl + '}' + nl)

main()
